-- STARBOY: tabel opsional untuk menyimpan pesanan di Supabase.
-- Form website saat ini mengirim pesanan langsung ke WhatsApp dan belum
-- terhubung ke Supabase. Jalankan SQL ini hanya jika nanti ingin menambahkan
-- penyimpanan pesanan melalui backend/serverless function yang aman.

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  product_name text not null,
  size text not null,
  color text not null,
  quantity integer not null check (quantity > 0),
  shipping_address text not null,
  notes text,
  status text not null default 'new',
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;

